/** Inserta un pedido con tarjeta (el disparador de la base genera el evento). */
export async function insertOrder(db, code, overrides = {}) {
  // Seguro contra errores de uso: jamás se inserta un pedido de prueba en las tablas reales.
  if ((await db.query('SELECT current_schema() AS s')).rows[0].s === 'public') throw new Error('insertOrder solo se usa en esquemas temporales (aura_test_…)');
  const row = {
    status: 'pendiente', total: 100000, shipping_cost: 20000, payment_method: 'Tarjeta de crédito o débito (Pagopar)',
    pagopar_hash: `hash-${code}`, items: [{ code: 'DD161', quantity: 1 }], created_at: null, ...overrides,
  };
  const sql = `INSERT INTO orders (order_id, name, phone, address, status, total, shipping_cost, payment_method, pagopar_hash, items, created_at)
     VALUES ($1, 'NOMBRE PRIVADO', 'TEL PRIVADO', 'DIRECCION PRIVADA', $2, $3, $4, $5, $6, $7::jsonb, COALESCE($8::timestamptz, now())) RETURNING id`;
  const params = [code, row.status, row.total, row.shipping_cost, row.payment_method, row.pagopar_hash, JSON.stringify(row.items), row.created_at];
  if (!overrides.noEvents) return (await db.query(sql, params)).rows[0].id;
  // Como la migración: con los disparadores apagados no se genera ningún evento.
  const client = await db.connect();
  try {
    await client.query('BEGIN');
    await client.query('SET LOCAL session_replication_role = replica');
    const { rows } = await client.query(sql, params);
    await client.query('COMMIT');
    return rows[0].id;
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}

/**
 * Esquema temporal dentro del Postgres real de Supabase: copia la estructura de las tablas de `public`
 * (mismas columnas, checks e índices) y el disparador de `orders`. Se borra al terminar. No toca `public`.
 */
export async function createScratchSchema(adminUrl) {
  const admin = new pg.Pool({ connectionString: adminUrl, max: 2 });
  const schema = `aura_test_${randomBytes(4).toString('hex')}`;
  await admin.query(`CREATE SCHEMA ${schema}`);
  const like = table => admin.query(`CREATE TABLE ${schema}.${table} (LIKE public.${table} INCLUDING ALL)`);
  for (const table of ['orders', 'whatsapp_alerts', 'whatsapp_payment_checks', 'whatsapp_alert_budget', 'whatsapp_alert_tests', 'worker_cursors']) await like(table);
  await admin.query(`CREATE TABLE ${schema}.order_events (LIKE public.order_events INCLUDING ALL EXCLUDING DEFAULTS)`);
  await admin.query(`ALTER TABLE ${schema}.order_events ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY, ALTER COLUMN created_at SET DEFAULT now()`);
  const { rows } = await admin.query(`SELECT pg_get_functiondef('public.log_order_event'::regproc) AS def`);
  const def = rows[0].def
    .replace('public.log_order_event', `${schema}.log_order_event`)
    .replaceAll('public.order_events', `${schema}.order_events`)
    .replace(/SET search_path TO '?public'?/i, `SET search_path TO ${schema}`);
  if (def.includes('public.')) throw new Error('El disparador de prueba aún apunta a public: no se continúa.');
  await admin.query(def);
  await admin.query(`CREATE TRIGGER orders_event_log AFTER INSERT OR UPDATE ON ${schema}.orders FOR EACH ROW EXECUTE FUNCTION ${schema}.log_order_event()`);
  const drop = async () => {
    if (!/^aura_test_[a-f0-9]{8}$/.test(schema)) throw new Error('Nombre de esquema inesperado');
    await admin.query(`DROP SCHEMA ${schema} CASCADE`);
    await admin.end();
  };
  return { schema, admin, drop, urlFor: url => `${url}${url.includes('?') ? '&' : '?'}options=${encodeURIComponent(`-c search_path=${schema}`)}` };
}
