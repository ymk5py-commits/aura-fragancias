/** YCloud y Pagopar simulados: ninguna prueba toca la red. */
export function createFakeNetwork() {
  const net = {
    sent: [], gets: [], estado: [], mode: 'accepted', paymentMode: 'pending', deliveryStatus: 'delivered',
    async fetch(url, init = {}) {
      const target = String(url);
      if (target.startsWith('https://www.aurafragancias.store/api/pagopar/estado?hash=')) {
        const hash = new URL(target).searchParams.get('hash');
        net.estado.push(hash);
        return Response.json({ hash, orderId: hash.slice(5), monto: '120000', pagado: net.paymentMode === 'paid', cancelado: false });
      }
      if (!target.startsWith('https://api.ycloud.com/v2/whatsapp/messages')) throw new Error(`Solicitud de red inesperada: ${target}`);
      if (init.method === 'POST') {
        net.sent.push(JSON.parse(init.body));
        if (net.mode === 'timeout') throw new Error('Conexión interrumpida simulada');
        if (net.mode === 'rate-limit') return new Response('{}', { status: 429 });
        return Response.json({ id: `ycloud-local-${net.sent.length}`, status: 'accepted' });
      }
      net.gets.push(target);
      return Response.json({ status: net.deliveryStatus });
    },
  };
  return net;
}

